import assert from 'node:assert/strict';
import {readFileSync,existsSync,mkdirSync} from 'node:fs';
import {chromium} from 'playwright';
import {build} from 'esbuild';
import {pathToFileURL} from 'node:url';
const engineVersion=JSON.parse(readFileSync('src/simulation/version.json','utf8'));
await build({entryPoints:['tests/dungeon-fixture.ts'],outfile:'.cache/browser-dungeon.mjs',bundle:true,platform:'node',format:'esm'});
const {leagueFixture}=await import(pathToFileURL(process.cwd()+'/.cache/browser-dungeon.mjs').href);
const executablePath=process.env.CHROMIUM_PATH||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':chromium.executablePath());
const browser=await chromium.launch({executablePath,headless:true,args:['--no-sandbox']});
try{
  const page=await browser.newPage({viewport:{width:1280,height:1000}}),requests=[],errors=[];
  page.on('request',r=>requests.push(r.url()));page.on('pageerror',e=>errors.push(String(e)));
  await page.route('**/*',r=>{
    const url=r.request().url();
    if(url===engineVersion.boot)return r.fulfill({contentType:'application/javascript',body:`window.BUNDLE=${JSON.stringify(engineVersion.url)}`});
    if(url===engineVersion.url)return r.fulfill({contentType:'application/javascript',body:readFileSync('.cache/engine.js','utf8')});
    return r.fulfill({contentType:'text/html',body:'<!doctype html><meta charset="utf-8"><style>body{background:#10151d}</style>'});
  });
  await page.goto('https://pokecatch-online.pages.dev/');
  const league=leagueFixture(readFileSync('.cache/engine.js','utf8')),forecastSave=league.entry;
  await page.evaluate(s=>localStorage.setItem('gachamon-save-v1',JSON.stringify(s)),league.entry);
  await page.addScriptTag({content:readFileSync('pokecatch-tools.user.js','utf8')});
  const float=page.getByTestId('farming-window');
  mkdirSync('test-results',{recursive:true});
  if(await page.getByTestId('fold').getAttribute('aria-expanded')==='false')await page.getByTestId('fold').click();
  await page.getByRole('tab',{name:'对策',exact:true}).click();await page.getByTestId('load-box').click();
  await page.getByTestId('counter-phase').filter({hasText:'已读取快照'}).waitFor({timeout:30000});
  assert.match(await page.getByTestId('counter-chapter').innerText(),/神奥联盟/);
  const fixedGoal=await page.getByTestId('plan-goal').innerText();assert.match(fixedGoal,/联盟冠军/);
  await page.getByTestId('run-team-plan').click();await page.getByTestId('counter-phase').filter({hasText:'配队完成'}).waitFor({timeout:120000});
  const fixedReport=await page.getByTestId('plan-baseline').innerText(),beforeAdvance=requests.filter(url=>url===engineVersion.boot).length;
  await page.evaluate(s=>localStorage.setItem('gachamon-save-v1',JSON.stringify(s)),league.next);
  await page.getByTestId('dungeon-progress').filter({hasText:'菊野'}).waitFor({timeout:10000});
  assert.equal(await page.getByTestId('plan-goal').innerText(),fixedGoal);
  assert.equal(await page.getByTestId('plan-baseline').innerText(),fixedReport);
  assert.equal(requests.filter(url=>url===engineVersion.boot).length,beforeAdvance);
  await page.getByTestId('run-team-plan').click();await page.getByTestId('counter-phase').filter({hasText:'配队完成'}).waitFor({timeout:120000});
  assert.equal(await page.getByTestId('plan-goal').innerText(),fixedGoal);
  assert.match(await page.getByTestId('plan-baseline').innerText(),/联盟/);
  console.log('PASS: league-stage progress preserves the dungeon goal and report without reload; recalculation keeps the same champion target');
  const nodeSave=JSON.parse(JSON.stringify(forecastSave));nodeSave.mons.forEach(m=>{m.level=68;m.xp=0;delete m.hp;});
  nodeSave.adv.chapter=59;nodeSave.adv.unlocked=59;nodeSave.adv.node=0;nodeSave.adv.battle=null;
  nodeSave.adv.nodes=[{type:'trainer',name:'同名路段',trainer:'测试',sprite:'youngster',bg:'cave',team:[[10,1]]},{type:'heal',name:'Frimapic',bg:'town'},
    {type:'trainer',name:'同名路段',trainer:'测试',sprite:'youngster',bg:'cave',team:[[10,1]]}];
  await page.evaluate(s=>localStorage.setItem('gachamon-save-v1',JSON.stringify(s)),nodeSave);
  await float.getByRole('button',{name:'本图节点',exact:true}).click();
  const nodeTrials=float.getByLabel('节点经验模拟次数').locator('input');await nodeTrials.fill('128');await nodeTrials.press('Tab');
  await float.getByTestId('run-node-xp').click();await float.getByTestId('node-xp-phase').filter({hasText:'节点计算完成'}).waitFor({timeout:60000});
  assert.equal(await float.getByTestId('node-xp-row').count(),3);
  assert.match(await float.getByTestId('node-xp-row').nth(1).innerText(),/\+0 XP/);
  const nodeDownload=page.waitForEvent('download');await float.getByTestId('export-node-xp').click();
  const nodeFile=await nodeDownload,nodeReport=JSON.parse(readFileSync(await nodeFile.path(),'utf8'));
  assert.equal(nodeReport.rows.length,3);assert.ok(Math.abs(nodeReport.rows.reduce((sum,n)=>sum+n.metric.xp.mean,0)-nodeReport.xp.mean)<1e-6);
  assert.equal(await page.evaluate(()=>localStorage.getItem('gachamon-save-v1')),JSON.stringify(nodeSave));
  await page.screenshot({path:'test-results/node-experience.png'});
  nodeSave.adv.node=1;await page.evaluate(s=>localStorage.setItem('gachamon-save-v1',JSON.stringify(s)),nodeSave);
  await float.getByTestId('node-xp-stale').waitFor();
  await float.getByLabel('节点经验计算范围').click();await page.getByText('剩余副本预估：保留当前 HP 和这场战斗',{exact:true}).click();
  await float.getByTestId('run-node-xp').click();await float.getByTestId('node-xp-phase').filter({hasText:'节点计算完成'}).waitFor({timeout:60000});
  assert.match(await float.getByTestId('node-xp-row').first().innerText(),/已通过，本次未回算/);
  assert.equal(await page.evaluate(()=>localStorage.getItem('gachamon-save-v1')),JSON.stringify(nodeSave));
  console.log('PASS: exact saved-node XP, zero-XP centers, conserved totals, export, stale progress and remaining-route scope');
  assert.deepEqual(errors,[]);
  assert.ok(requests.every(url=>['https://pokecatch-online.pages.dev/',engineVersion.boot,engineVersion.url].includes(url)));
  await page.evaluate(()=>window.__pcToolsDispose());
  console.log('PASS: no browser errors, external game requests or game-save writes');
}finally{await browser.close();}
